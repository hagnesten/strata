	static void identity_columns ( engine::database& db ) {

		run ( db, "CREATE TABLE dialect_items ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT COLLATE \"C\" NOT NULL, price DOUBLE PRECISION )" );
		run ( db, "INSERT INTO dialect_items ( name, price ) VALUES ( 'a', 1.5 ), ( 'b', 2.5 )" );
		rows ( db, "SELECT id, name, price FROM dialect_items ORDER BY id", "1|a|1.5\n2|b|2.5" );
		plan_has ( db, "EXPLAIN QUERY PLAN SELECT name FROM dialect_items WHERE id = 2", "rowid" );
		run ( db, "CREATE TABLE dialect_serial ( id serial PRIMARY KEY, note TEXT )" );
		run ( db, "INSERT INTO dialect_serial ( note ) VALUES ( 'x' )" );
		rows ( db, "SELECT id, note FROM dialect_serial", "1|x" );
		run ( db, "DROP TABLE dialect_serial" );
		run ( db, "CREATE TABLE dialect_serial ( id bigserial, note TEXT, PRIMARY KEY ( id ) )" );
		run ( db, "INSERT INTO dialect_serial ( note ) VALUES ( 'x' ), ( 'y' )" );
		rows ( db, "SELECT max ( id ) FROM dialect_serial", "2" );
		fails ( db, "CREATE TABLE dialect_bad ( id serial, note TEXT )", "PRIMARY KEY" );
		fails ( db, "CREATE TABLE dialect_bad ( id TEXT GENERATED ALWAYS AS IDENTITY PRIMARY KEY )", "integer type" );
		run ( db, "DROP TABLE dialect_serial" );
		run ( db, "DROP TABLE dialect_items" );

	}

	static void schemas ( engine::database& db ) {

		run ( db, "CREATE SCHEMA IF NOT EXISTS dialect_space" );
		run ( db, "CREATE TABLE dialect_space.prices ( id INTEGER PRIMARY KEY, v INTEGER )" );
		run ( db, "CREATE TABLE prices ( id INTEGER PRIMARY KEY, v INTEGER )" );
		run ( db, "INSERT INTO dialect_space.prices VALUES ( 1, 10 )" );
		run ( db, "INSERT INTO public.prices VALUES ( 1, 99 )" );
		rows ( db, "SELECT prices.v FROM dialect_space.prices", "10" );
		rows ( db, "SELECT v FROM prices", "99" );

		expect ( engine::set_search ( *db.schema, "dialect_space" ), "search_path takes a schema" );
		rows ( db, "SELECT v FROM prices", "10" );
		run ( db, "CREATE TABLE ticks ( id INTEGER PRIMARY KEY, p REAL )" );
		run ( db, "INSERT INTO ticks VALUES ( 1, 2.5 )" );
		rows ( db, "SELECT p FROM dialect_space.ticks", "2.5" );
		expect ( engine::set_search ( *db.schema, "public" ), "search_path goes back to public" );

		rows ( db, "SELECT v FROM prices", "99" );
		fails ( db, "SELECT p FROM ticks", "no such table" );
		fails ( db, "DROP SCHEMA dialect_space", "CASCADE" );
		run ( db, "DROP SCHEMA dialect_space CASCADE" );
		fails ( db, "SELECT v FROM dialect_space.prices", "no such table" );
		rows ( db, "SELECT v FROM prices", "99" );
		run ( db, "DROP SCHEMA IF EXISTS dialect_space CASCADE" );
		run ( db, "DROP TABLE prices" );

	}

	static void returning_rows ( engine::database& db ) {

		run ( db, "CREATE TABLE dialect_fills ( id BIGSERIAL PRIMARY KEY, symbol TEXT, qty INTEGER, price DOUBLE PRECISION )" );
		rows ( db, "INSERT INTO dialect_fills ( symbol, qty, price ) VALUES ( 'AAPL', 100, 10.5 ), ( 'MSFT', 5, 2.0 ) RETURNING id, qty * price AS notional", "1|1050.0\n2|10.0" );
		rows ( db, "UPDATE dialect_fills SET qty = qty - 40 WHERE symbol = 'AAPL' RETURNING *", "1|AAPL|60|10.5" );
		rows ( db, "UPDATE dialect_fills SET qty = 0 WHERE id = 99 RETURNING id", "" );
		rows ( db, "DELETE FROM dialect_fills WHERE id = 2 RETURNING symbol, id", "MSFT|2" );
		rows ( db, "INSERT INTO dialect_fills ( symbol, qty, price ) SELECT 'IBM', 1, 3.0 RETURNING dialect_fills.id", "3" );
		rows ( db, "SELECT count ( * ) FROM dialect_fills", "2" );
		run ( db, "DELETE FROM dialect_fills WHERE id = 3" );
		rows ( db, "INSERT INTO dialect_fills ( symbol, qty, price ) VALUES ( 'TSLA', 2, 1.0 ) RETURNING id", "4" );
		run ( db, "DELETE FROM dialect_fills" );
		rows ( db, "INSERT INTO dialect_fills ( symbol, qty, price ) VALUES ( 'NVDA', 2, 1.0 ) RETURNING id", "5" );
		run ( db, "DROP TABLE dialect_fills" );
		run ( db, "CREATE TABLE dialect_fills ( id BIGSERIAL PRIMARY KEY, symbol TEXT )" );
		rows ( db, "INSERT INTO dialect_fills ( symbol ) VALUES ( 'AMD' ) RETURNING id", "1" );
		run ( db, "DROP TABLE dialect_fills" );
		run ( db, "CREATE TABLE dialect_plain ( id INTEGER PRIMARY KEY, v TEXT )" );
		run ( db, "INSERT INTO dialect_plain ( v ) VALUES ( 'a' ), ( 'b' )" );
		run ( db, "DELETE FROM dialect_plain WHERE id = 2" );
		rows ( db, "INSERT INTO dialect_plain ( v ) VALUES ( 'c' ) RETURNING id", "2" );
		run ( db, "DROP TABLE dialect_plain" );

	}

	static void expressions ( engine::database& db ) {

		rows ( db, "SELECT '42'::int + 1, 7::text || 'x', 'TRUE'::boolean, 'off'::bool, '2024-01-02'::timestamp with time zone, 1.5::numeric ( 10, 2 )", "43|7x|1|0|2024-01-02|1.5" );
		rows ( db, "SELECT 'Apple' ILIKE 'a%', 'Apple' NOT ILIKE 'b%'", "1|1" );
		rows ( db, "SELECT current_database ( ), current_schema, current_user, length ( gen_random_uuid ( ) ), substr ( gen_random_uuid ( ), 15, 1 )", "strata|public|strata|36|4" );
		rows ( db, "SELECT version ( ) LIKE 'PostgreSQL 17%', length ( now ( ) ), current_setting ( 'server_version_num' )", "1|23|170000" );
		fails ( db, "SELECT 'maybe'::boolean", "boolean" );

	}

	static void catalog_views ( engine::database& db ) {

		run ( db, "CREATE TABLE dialect_orders ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, symbol VARCHAR ( 12 ) NOT NULL, placed TIMESTAMPTZ )" );
		run ( db, "CREATE INDEX dialect_orders_symbol ON dialect_orders ( symbol )" );
		rows ( db, "SELECT EXISTS ( SELECT 1 FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relname = 'dialect_orders' )", "1" );
		rows ( db, "SELECT attname, atttypid, attnotnull, attidentity FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid WHERE c.relname = 'dialect_orders' ORDER BY attnum", "id|20|1|d\nsymbol|1043|1|\nplaced|1184|0|" );
		rows ( db, "SELECT column_name, data_type, is_nullable FROM information_schema.columns WHERE table_name = 'dialect_orders' ORDER BY ordinal_position", "id|bigint|NO\nsymbol|character varying|NO\nplaced|timestamp with time zone|YES" );
		rows ( db, "SELECT count ( * ) FROM pg_index i JOIN pg_class c ON c.oid = i.indrelid WHERE c.relname = 'dialect_orders'", "2" );
		rows ( db, "SELECT typname FROM pg_type WHERE oid = 1185", "_timestamptz" );
		rows ( db, "SELECT count ( * ) FROM pg_enum", "0" );
		rows ( db, "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_name LIKE 'dialect%'", "dialect_orders" );
		run ( db, "DROP TABLE dialect_orders" );

	}

