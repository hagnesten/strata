using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using Strata.Wire;

namespace Strata.Replay {

	internal static class Copier {

		private static string Quote ( string name ) => "\"" + name.Replace ( "\"", "\"\"" ) + "\"";

		private static string Literal ( string value ) => "'" + value.Replace ( "'", "''" ) + "'";

		public static void Copy ( PgWire source, PgWire target, TextWriter log ) {

			PgResult tables = source.Query ( "SELECT c.relname FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY 1" ) [ 0 ];

			foreach ( object [ ] row in tables.Rows ) {

				string table = ( string ) row [ 0 ];
				string reference = Literal ( Quote ( table ) );
				PgResult columns = source.Query ( "SELECT a.attname, pg_catalog.format_type ( a.atttypid, a.atttypmod ), a.attnotnull, a.attidentity, t.typname FROM pg_catalog.pg_attribute a JOIN pg_catalog.pg_type t ON t.oid = a.atttypid WHERE a.attrelid = " + reference + "::regclass AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum" ) [ 0 ];
				PgResult keys = source.Query ( "SELECT a.attname FROM pg_catalog.pg_index i JOIN pg_catalog.pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY ( i.indkey ) WHERE i.indrelid = " + reference + "::regclass AND i.indisprimary ORDER BY array_position ( i.indkey, a.attnum )" ) [ 0 ];
				StringBuilder create = new StringBuilder ( "CREATE TABLE " + Quote ( table ) + " ( " );
				List < string > kinds = new List < string > ( );

				for ( int i = 0; i < columns.Rows.Count; i++ ) {

					object [ ] column = columns.Rows [ i ];
					string identity = column [ 3 ] as string;

					if ( i > 0 )
						create.Append ( ", " );

					create.Append ( Quote ( ( string ) column [ 0 ] ) ).Append ( ' ' ).Append ( ( string ) column [ 1 ] );

					if ( !string.IsNullOrEmpty ( identity ) )
						create.Append ( " GENERATED BY DEFAULT AS IDENTITY" );

					if ( ( string ) column [ 2 ] == "t" )
						create.Append ( " NOT NULL" );

					kinds.Add ( ( string ) column [ 4 ] );

				}

				if ( keys.Rows.Count > 0 ) {

					create.Append ( ", PRIMARY KEY ( " );

					for ( int i = 0; i < keys.Rows.Count; i++ )
						create.Append ( i > 0 ? ", " : "" ).Append ( Quote ( ( string ) keys.Rows [ i ] [ 0 ] ) );

					create.Append ( " )" );

				}

				create.Append ( " )" );
				target.Query ( "DROP TABLE IF EXISTS " + Quote ( table ) );
				target.Query ( create.ToString ( ) );

				PgResult data = source.Query ( "SELECT * FROM " + Quote ( table ) ) [ 0 ];
				StringBuilder insert = new StringBuilder ( );
				int pending = 0;

				target.Query ( "BEGIN" );

				foreach ( object [ ] values in data.Rows ) {

					insert.Append ( pending == 0 ? "INSERT INTO " + Quote ( table ) + " VALUES ( " : ", ( " );

					for ( int c = 0; c < values.Length; c++ ) {

						if ( c > 0 )
							insert.Append ( ", " );

						string text = values [ c ] as string;

						if ( text == null )
							insert.Append ( "NULL" );
						else if ( kinds [ c ] == "bool" )
							insert.Append ( text == "t" ? "TRUE" : "FALSE" );
						else if ( kinds [ c ] == "bytea" && text.StartsWith ( "\\x" ) )
							insert.Append ( "X'" ).Append ( text.Substring ( 2 ) ).Append ( '\'' );
						else
							insert.Append ( Literal ( text ) );

					}

					insert.Append ( " )" );

					if ( ++pending == 400 ) {

						target.Query ( insert.ToString ( ) );
						insert.Clear ( );
						pending = 0;

					}

				}

				if ( pending > 0 )
					target.Query ( insert.ToString ( ) );

				target.Query ( "COMMIT" );

				PgResult indexes = source.Query ( "SELECT indexdef FROM pg_catalog.pg_indexes i JOIN pg_catalog.pg_class c ON c.relname = i.indexname JOIN pg_catalog.pg_index x ON x.indexrelid = c.oid WHERE i.schemaname = 'public' AND i.tablename = " + Literal ( table ) + " AND NOT x.indisprimary" ) [ 0 ];
				int made = 0;

				foreach ( object [ ] index in indexes.Rows ) {

					string definition = ( ( string ) index [ 0 ] ).Replace ( " ON public.", " ON " );

					try {

						target.Query ( definition );
						made++;

					} catch ( PgException error ) {

						log.WriteLine ( "  index skipped: " + definition + " -> " + error.Message );

					}

				}

				log.WriteLine ( "copied " + table + ": " + data.Rows.Count + " rows, " + made + " indexes" );

			}

		}

	}

}
