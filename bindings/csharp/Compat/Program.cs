		private static void Concurrency ( Run run ) {

			using ( NpgsqlConnection connection = Open ( run ) ) {

				Exec ( connection, "DROP TABLE IF EXISTS busy_orders" );
				Exec ( connection, "CREATE TABLE busy_orders ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, client INTEGER NOT NULL, n INTEGER NOT NULL )" );
				Exec ( connection, "DROP TABLE IF EXISTS busy_balance" );
				Exec ( connection, "CREATE TABLE busy_balance ( id INTEGER PRIMARY KEY, cash BIGINT NOT NULL )" );
				Exec ( connection, "INSERT INTO busy_balance VALUES ( 1, 0 )" );

			}

			const int clients = 16;
			const int each = 100;

			Parallel.For ( 0, clients, new ParallelOptions { MaxDegreeOfParallelism = clients }, client => {

				using NpgsqlConnection connection = Open ( run );

				for ( int i = 0; i < each; i++ ) {

					using NpgsqlTransaction transaction = connection.BeginTransaction ( );
					using NpgsqlCommand insert = new NpgsqlCommand ( "INSERT INTO busy_orders ( client, n ) VALUES ( @c, @n )", connection, transaction );

					insert.Parameters.AddWithValue ( "c", client );
					insert.Parameters.AddWithValue ( "n", i );
					insert.ExecuteNonQuery ( );

					using NpgsqlCommand bump = new NpgsqlCommand ( "UPDATE busy_balance SET cash = cash + 1 WHERE id = 1", connection, transaction );

					bump.ExecuteNonQuery ( );
					transaction.Commit ( );

				}

			} );

			using NpgsqlConnection check = Open ( run );
			using NpgsqlCommand totals = new NpgsqlCommand ( "SELECT count ( * ), count ( DISTINCT id ), ( SELECT cash FROM busy_balance WHERE id = 1 ) FROM busy_orders", check );
			using NpgsqlDataReader reader = totals.ExecuteReader ( );

			reader.Read ( );
			run.Note ( "concurrency.orders", reader.GetInt64 ( 0 ) );
			run.Note ( "concurrency.distinct", reader.GetInt64 ( 1 ) );
			run.Note ( "concurrency.balance", reader.GetInt64 ( 2 ) );

		}

		private static void Notify ( Run run ) {

			using NpgsqlConnection listener = Open ( run );
			using NpgsqlConnection sender = Open ( run );
			List < string > heard = new List < string > ( );

			listener.Notification += ( _, e ) => heard.Add ( e.Channel + ":" + e.Payload + ":" + ( e.PID == sender.ProcessID ) );
			Exec ( listener, "LISTEN fills; LISTEN \"Order Book\"" );
			Exec ( sender, "NOTIFY fills, 'order 42 filled 100 @ 187.25'" );
			Exec ( sender, "NOTIFY \"Order Book\", 'it''s quoted; with a semicolon'" );
			Exec ( sender, "NOTIFY other, 'nobody listens'" );

			using ( NpgsqlTransaction kept = sender.BeginTransaction ( ) ) {

				Exec ( sender, "NOTIFY fills, 'after commit'" );
				kept.Commit ( );

			}

			using ( NpgsqlTransaction dropped = sender.BeginTransaction ( ) ) {

				Exec ( sender, "NOTIFY fills, 'rolled back'" );
				dropped.Rollback ( );

			}

			Exec ( sender, "NOTIFY fills" );

			for ( int i = 0; i < 20 && heard.Count < 4; i++ )
				listener.Wait ( 100 );

			run.Note ( "notify.heard", heard );
			Exec ( listener, "UNLISTEN fills" );
			Exec ( sender, "NOTIFY fills, 'ignored'" );
			listener.Wait ( 200 );
			run.Note ( "notify.after_unlisten", heard.Count );

		}

		private static void Speed ( Run run, int count ) {

			using NpgsqlConnection connection = Open ( run );

			Exec ( connection, "DROP TABLE IF EXISTS speed_orders" );
			Exec ( connection, "CREATE TABLE speed_orders ( id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, symbol VARCHAR ( 16 ) NOT NULL, quantity INTEGER NOT NULL, price NUMERIC ( 18, 4 ) NOT NULL, placed TIMESTAMPTZ NOT NULL )" );
			Exec ( connection, "CREATE INDEX speed_symbol ON speed_orders ( symbol )" );

			Stopwatch clock = Stopwatch.StartNew ( );

			using ( NpgsqlCommand insert = new NpgsqlCommand ( "INSERT INTO speed_orders ( symbol, quantity, price, placed ) VALUES ( @s, @q, @p, @t ) RETURNING id", connection ) ) {

				NpgsqlParameter symbol = insert.Parameters.Add ( "s", NpgsqlDbType.Varchar );
				NpgsqlParameter quantity = insert.Parameters.Add ( "q", NpgsqlDbType.Integer );
				NpgsqlParameter price = insert.Parameters.Add ( "p", NpgsqlDbType.Numeric );
				NpgsqlParameter placed = insert.Parameters.Add ( "t", NpgsqlDbType.TimestampTz );

				insert.Prepare ( );

				for ( int i = 0; i < count; i++ ) {

					symbol.Value = Symbols [ i % Symbols.Length ];
					quantity.Value = i;
					price.Value = 100m + i * 0.0001m;
					placed.Value = Base.AddMilliseconds ( i );
					insert.ExecuteScalar ( );

				}

			}

			run.Times [ "speed.insert_autocommit" ] = clock.Elapsed.TotalMilliseconds * 1000 / count;
			clock.Restart ( );

			using ( NpgsqlTransaction transaction = connection.BeginTransaction ( ) )
			using ( NpgsqlCommand insert = new NpgsqlCommand ( "INSERT INTO speed_orders ( symbol, quantity, price, placed ) VALUES ( @s, @q, @p, @t )", connection, transaction ) ) {

				NpgsqlParameter symbol = insert.Parameters.Add ( "s", NpgsqlDbType.Varchar );
				NpgsqlParameter quantity = insert.Parameters.Add ( "q", NpgsqlDbType.Integer );
				NpgsqlParameter price = insert.Parameters.Add ( "p", NpgsqlDbType.Numeric );
				NpgsqlParameter placed = insert.Parameters.Add ( "t", NpgsqlDbType.TimestampTz );

				insert.Prepare ( );

				for ( int i = 0; i < count * 10; i++ ) {

					symbol.Value = Symbols [ i % Symbols.Length ];
					quantity.Value = i;
					price.Value = 100m + i * 0.0001m;
					placed.Value = Base.AddMilliseconds ( i );
					insert.ExecuteNonQuery ( );

				}

				transaction.Commit ( );

			}

			run.Times [ "speed.insert_in_transaction" ] = clock.Elapsed.TotalMilliseconds * 1000 / ( count * 10 );
			clock.Restart ( );

			using ( NpgsqlCommand lookup = new NpgsqlCommand ( "SELECT id, quantity, price FROM speed_orders WHERE id = @id", connection ) ) {

				NpgsqlParameter id = lookup.Parameters.Add ( "id", NpgsqlDbType.Bigint );

