					id.Value = ( long ) ( 1 + i * 7 % ( count * 11 ) );

					using NpgsqlDataReader reader = lookup.ExecuteReader ( );

					reader.Read ( );

				}

			}

			run.Times [ "speed.point_lookup" ] = clock.Elapsed.TotalMilliseconds * 1000 / count;
			clock.Restart ( );

			using ( NpgsqlCommand aggregate = new NpgsqlCommand ( "SELECT symbol, count ( * ), sum ( quantity ), avg ( price ) FROM speed_orders GROUP BY symbol ORDER BY symbol", connection ) ) {

				for ( int i = 0; i < 20; i++ ) {

					using NpgsqlDataReader reader = aggregate.ExecuteReader ( );

					while ( reader.Read ( ) ) {

