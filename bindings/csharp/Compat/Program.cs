		public static string Show ( object value ) {

			switch ( value ) {

				case null: return "NULL";
				case DBNull _: return "NULL";
				case DateTime time: return time.ToString ( "yyyy-MM-dd'T'HH:mm:ss.ffffff", CultureInfo.InvariantCulture ) + " " + time.Kind;
				case DateOnly date: return date.ToString ( "yyyy-MM-dd", CultureInfo.InvariantCulture );
				case decimal number: return number.ToString ( CultureInfo.InvariantCulture ) + "m";
				case double number: return number.ToString ( "R", CultureInfo.InvariantCulture ) + "d";
				case float number: return number.ToString ( "R", CultureInfo.InvariantCulture ) + "f";
				case byte [ ] bytes: return "0x" + Convert.ToHexString ( bytes );
				case bool flag: return flag ? "true" : "false";
				case string text: return "'" + text + "'";
				case System.Collections.IEnumerable list: return "[" + string.Join ( ", ", list.Cast < object > ( ).Select ( Show ) ) + "]";
				default: return Convert.ToString ( value, CultureInfo.InvariantCulture ) + " " + value.GetType ( ).Name;

			}

		}

		private static void Step ( Run run, string name, Action action ) {

			Stopwatch clock = Stopwatch.StartNew ( );

			try {

				action ( );

			} catch ( Exception error ) {

				Exception inner = error is AggregateException many ? many.InnerExceptions [ 0 ] : error;
				PostgresException postgres = inner as PostgresException ?? inner.InnerException as PostgresException;

				run.Note ( name + ".error", postgres != null ? "SQLSTATE " + postgres.SqlState : inner.GetType ( ).Name );
				run.Messages.Add ( name + ": " + inner.GetType ( ).Name + ": " + inner.Message.Split ( '\n' ) [ 0 ] );

			}

			clock.Stop ( );
			run.Times [ name ] = clock.Elapsed.TotalMilliseconds;

		}

