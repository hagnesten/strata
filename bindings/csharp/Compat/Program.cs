				}

			}

			run.Times [ "speed.group_by_scan" ] = clock.Elapsed.TotalMilliseconds * 1000 / 20;

		}

		private static Run Execute ( string name, string connection, int speed ) {

			Run run = new Run { Name = name, Connection = connection };

			Console.WriteLine ( "running " + name );
			Step ( run, "open", ( ) => { using NpgsqlConnection c = Open ( run ); run.Note ( "open.version", c.PostgreSqlVersion.Major ); } );
			Step ( run, "types", ( ) => Types ( run ) );
			Step ( run, "money", ( ) => Money ( run ) );
			Step ( run, "errors", ( ) => Errors ( run ) );
			Step ( run, "dapper", ( ) => Dapper ( run ) );
			Step ( run, "batches", ( ) => Batches ( run ) );
			Step ( run, "entity", ( ) => Entity ( run ) );
			Step ( run, "concurrency", ( ) => Concurrency ( run ) );
			Step ( run, "notify", ( ) => Notify ( run ) );

			if ( speed > 0 )
				Step ( run, "speed", ( ) => Speed ( run, speed ) );

			NpgsqlConnection.ClearAllPools ( );

			return run;

		}

		private static int Main ( string [ ] args ) {

			string postgres = null;
			string strata = null;
			int speed = 2000;

			for ( int i = 0; i + 1 < args.Length; i++ ) {

				if ( args [ i ] == "--postgres" )
					postgres = args [ i + 1 ];
				else if ( args [ i ] == "--strata" )
					strata = args [ i + 1 ];
				else if ( args [ i ] == "--speed" )
					speed = int.Parse ( args [ i + 1 ], CultureInfo.InvariantCulture );

			}

			if ( postgres == null || strata == null ) {

				Console.WriteLine ( "usage: Strata.Compat --postgres <connection> --strata <connection> [--speed rows]" );

				return 2;

			}

			Run reference = Execute ( "postgres", postgres, speed );
			Run candidate = Execute ( "strata", strata, speed );
			Dictionary < string, string > expected = new Dictionary < string, string > ( );
			Dictionary < string, string > actual = new Dictionary < string, string > ( );

			foreach ( var line in reference.Lines )
				expected [ line.Key ] = line.Value;

			foreach ( var line in candidate.Lines )
				actual [ line.Key ] = line.Value;

			int same = 0;
			int different = 0;

			foreach ( string key in expected.Keys.Union ( actual.Keys ) ) {

				expected.TryGetValue ( key, out string want );
				actual.TryGetValue ( key, out string got );

				if ( want == got ) {

					same++;

					continue;

				}

				different++;
				Console.WriteLine ( "DIFF " + key );
				Console.WriteLine ( "     postgres: " + ( want ?? "(missing)" ) );
				Console.WriteLine ( "     strata:   " + ( got ?? "(missing)" ) );

			}

			foreach ( string message in candidate.Messages )
				Console.WriteLine ( "strata said    " + message );

			foreach ( string message in reference.Messages )
				Console.WriteLine ( "postgres said  " + message );

			Console.WriteLine ( );
			Console.WriteLine ( "timing                         postgres      strata" );

			foreach ( string key in reference.Times.Keys )
				Console.WriteLine ( string.Format ( CultureInfo.InvariantCulture, "  {0,-26} {1,10:N1} {2,11:N1}{3}", key, reference.Times [ key ], candidate.Times.TryGetValue ( key, out double t ) ? t : double.NaN, key.StartsWith ( "speed." ) ? "  us/op" : "  ms" ) );

			Console.WriteLine ( );
			Console.WriteLine ( same + " results match, " + different + " differ" );

			return different == 0 ? 0 : 1;

		}

