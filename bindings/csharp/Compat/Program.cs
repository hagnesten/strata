			Exec ( connection, "CREATE TABLE errors_check ( id INTEGER PRIMARY KEY, code TEXT NOT NULL UNIQUE )" );
			Exec ( connection, "INSERT INTO errors_check VALUES ( 1, 'a' )" );

			foreach ( var ( name, sql ) in new [ ] {
				( "unique", "INSERT INTO errors_check VALUES ( 2, 'a' )" ),
				( "primary", "INSERT INTO errors_check VALUES ( 1, 'b' )" ),
				( "not_null", "INSERT INTO errors_check VALUES ( 3, NULL )" ),
				( "syntax", "SELEC 1" ),
				( "missing_table", "SELECT * FROM no_such_table" ),
				( "missing_column", "SELECT no_such_column FROM errors_check" ),
				( "divide", "SELECT 1 / 0" ),
				( "cast", "SELECT 'abc'::int" ),
			} ) {

				try {

					Exec ( connection, sql );
					run.Note ( "errors." + name, "no error" );

				} catch ( PostgresException error ) {

					run.Note ( "errors." + name, error.SqlState );
					run.Messages.Add ( "errors." + name + ": " + error.MessageText );

				}

			}

			using ( NpgsqlTransaction transaction = connection.BeginTransaction ( ) ) {

				Exec ( connection, "INSERT INTO errors_check VALUES ( 10, 'x' )" );

				try {

					Exec ( connection, "INSERT INTO errors_check VALUES ( 10, 'y' )" );

				} catch ( PostgresException error ) {

					run.Note ( "errors.in_transaction", error.SqlState );

				}

				try {

					Exec ( connection, "INSERT INTO errors_check VALUES ( 11, 'z' )" );
					run.Note ( "errors.after_failure", "accepted" );

				} catch ( PostgresException error ) {

					run.Note ( "errors.after_failure", error.SqlState );

				}

				transaction.Rollback ( );

			}

			using NpgsqlCommand count = new NpgsqlCommand ( "SELECT count ( * ) FROM errors_check", connection );

			run.Note ( "errors.rows_after_rollback", count.ExecuteScalar ( ) );

		}

